import React from 'react';
import { Download, FileText, CheckCircle2, Sparkles, Building2, Eye, Play, Loader2, Clock } from 'lucide-react';
import StatusBadge from '../components/StatusBadge';

export default function Reports({ calls, onDownloadReport, onSelectCall, onAnalyzeCall, analyzingIds }) {
  const readyCount = calls.filter((c) => c.analysis_status === 'completed').length;
  const pendingCount = calls.length - readyCount;

  return (
    <div className="space-y-6 animate-in fade-in duration-200">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <h1 className="text-2xl sm:text-3xl font-bold tracking-tight text-slate-900">
            Dossiers &amp; Call Reports
          </h1>
          <p className="text-sm text-slate-500 mt-1">
            Download executive PDF summaries generated by the FastAPI + ReportLab backend.
          </p>
        </div>
        <div className="flex items-center gap-2">
          <div className="inline-flex items-center gap-2 px-3 py-1.5 rounded-xl bg-emerald-50 text-emerald-700 border border-emerald-100 text-xs font-semibold">
            <FileText className="w-4 h-4" />
            <span>{readyCount} Report{readyCount !== 1 ? 's' : ''} Ready</span>
          </div>
          {pendingCount > 0 && (
            <div className="inline-flex items-center gap-2 px-3 py-1.5 rounded-xl bg-amber-50 text-amber-700 border border-amber-100 text-xs font-semibold">
              <Clock className="w-4 h-4" />
              <span>{pendingCount} Pending Analysis</span>
            </div>
          )}
        </div>
      </div>

      {pendingCount > 0 && (
        <div className="p-4 rounded-2xl bg-indigo-50/60 border border-indigo-100/80 flex items-start gap-3">
          <div className="w-8 h-8 rounded-xl bg-indigo-100 text-indigo-700 flex items-center justify-center shrink-0 mt-0.5">
            <Sparkles className="w-4 h-4" />
          </div>
          <div className="text-xs text-indigo-950 space-y-1">
            <div className="font-bold">Analysis Required Before Download</div>
            <p className="text-slate-600 leading-relaxed">
              {pendingCount} call{pendingCount !== 1 ? 's' : ''} still need{pendingCount === 1 ? 's' : ''} to be analyzed. Click "Analyze" on any pending row to run Whisper transcription and Gemini AI analysis before generating the PDF report.
            </p>
          </div>
        </div>
      )}

      {/* Reports Table */}
      <div className="bg-white border border-slate-200/90 rounded-2xl shadow-xs overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left border-collapse">
            <thead>
              <tr className="bg-slate-50/80 border-b border-slate-200/80 text-[11px] font-semibold text-slate-500 uppercase tracking-wider">
                <th className="py-3.5 px-4 pl-6">Call ID</th>
                <th className="py-3.5 px-4">Recording</th>
                <th className="py-3.5 px-4">Analysis Status</th>
                <th className="py-3.5 px-4">Report</th>
                <th className="py-3.5 px-4 pr-6 text-right">Action</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 text-sm">
              {calls.map((call) => {
                const isCompleted = call.analysis_status === 'completed';
                const isAnalyzing = analyzingIds?.has(call.call_id);
                const callLabel = call.call_label || `Call #${call.call_id.replace('CALL-', '')}`;

                return (
                  <tr key={call.call_id} className="hover:bg-slate-50/70 transition-colors">
                    {/* Call ID */}
                    <td className="py-4 px-4 pl-6 font-mono text-xs font-semibold text-indigo-600">
                      <span className="px-2 py-0.5 rounded-md bg-indigo-50 border border-indigo-100">
                        {call.call_id}
                      </span>
                    </td>

                    {/* Recording */}
                    <td className="py-4 px-4">
                      <div className="font-semibold text-slate-800">{callLabel}</div>
                      <div className="text-xs text-slate-400 font-mono mt-0.5">
                        {call.original_filename || 'audio.mp4'}
                      </div>
                    </td>

                    {/* Analysis Status */}
                    <td className="py-4 px-4">
                      {isAnalyzing ? (
                        <span className="inline-flex items-center gap-1.5 text-xs text-amber-700">
                          <Loader2 className="w-3.5 h-3.5 animate-spin" />
                          Analyzing…
                        </span>
                      ) : (
                        <StatusBadge status={call.analysis_status} />
                      )}
                    </td>

                    {/* Report */}
                    <td className="py-4 px-4">
                      {isCompleted ? (
                        <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-emerald-50 text-emerald-700 border border-emerald-200/60">
                          <CheckCircle2 className="w-3 h-3" />
                          Available
                        </span>
                      ) : (
                        <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-slate-50 text-slate-400 border border-slate-200">
                          Not ready
                        </span>
                      )}
                    </td>

                    {/* Action */}
                    <td className="py-4 px-4 pr-6 text-right">
                      <div className="inline-flex items-center gap-2">
                        <button
                          onClick={() => onSelectCall(call)}
                          className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 transition-colors"
                        >
                          <Eye className="w-3.5 h-3.5" />
                          <span>View</span>
                        </button>

                        {isCompleted ? (
                          <button
                            onClick={() => onDownloadReport(call)}
                            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold text-white bg-indigo-600 hover:bg-indigo-700 shadow-2xs transition-colors"
                          >
                            <Download className="w-3.5 h-3.5" />
                            <span>Download PDF</span>
                          </button>
                        ) : isAnalyzing ? (
                          <span className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold text-amber-600 bg-amber-50">
                            <Loader2 className="w-3.5 h-3.5 animate-spin" />
                            Running…
                          </span>
                        ) : (
                          <button
                            onClick={() => onAnalyzeCall?.(call)}
                            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold text-emerald-700 bg-emerald-50 hover:bg-emerald-100 border border-emerald-200 transition-colors"
                          >
                            <Play className="w-3.5 h-3.5" />
                            <span>Analyze</span>
                          </button>
                        )}
                      </div>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
